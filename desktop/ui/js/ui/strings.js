export function preferredLocale() {
  const nav = globalThis.navigator;
  const languages = nav?.languages?.length ? nav.languages : [nav?.language || 'en'];
  return languages.some((language) => /^fa(?:-|$)/i.test(language)) ? 'fa' : 'en';
}

export let APP_LOCALE = preferredLocale();
export let IS_RTL = APP_LOCALE === 'fa';
export const S = {};

function refreshStrings() {
  for (const key of Object.keys(S)) delete S[key];
  Object.assign(S, EN, IS_RTL ? FA : {});
}

export function resolveLanguage(value) {
  return value === 'fa' || value === 'en' ? value : preferredLocale();
}

export function setLanguage(value) {
  APP_LOCALE = resolveLanguage(value);
  IS_RTL = APP_LOCALE === 'fa';
  refreshStrings();
  refreshChoices();
}

refreshStrings();

